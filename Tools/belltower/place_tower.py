"""P10-5 bell tower / cloister / passage structure placement script (Unreal MCP).
Reads Docs/plans/p10_d1_layout.json (generated by gen_tower_layout.py; never hand-edit it). Adapted from Tools/crypt/place_crypt.py.

Usage (editor open on L_Monastery; no PIE; one editor-touching process at a time):
    python place_tower.py --cats block                    # place a category (idempotent: removes that category's actors first)
    python place_tower.py --cats wall --only PSA_         # only records whose id contains this text (removes only those)
    python place_tower.py --cats wall --check             # no edits: read back transform/bounds/collision/materials of the existing actors
    python place_tower.py --cats door --check --fix-collision   # re-apply NoCollision incl. collisionEnabled before checking
    python place_tower.py --hide-greybox                  # D1.0 / D-078: StaticMeshComponent.bVisible=false on the 280 hide_greybox labels
    python place_tower.py --verify-greybox                # read back bVisible + collision profile and run the trace checks
    python place_tower.py --ground                        # apply ground_materials (Ground_1..6) and read back the slab materials
    python place_tower.py --perim                         # apply perimeter_materials (Perim_N/E/S/W -> MI_Kit_Masonry); visibility and collision must stay unchanged

Placed categories: block wall tower stair arcade vault roof floor garth door doorleaf (P10-5) and dress (P10-6a, D1.20).
dress = static-mesh records (placed like the others) plus the 8 DecalActors (mesh "Point" with extras.decal: DecalActor, decalMaterial + decalSize,
  verified by material, size, transform, forward vector into the wall (dot >= 0.999) and a trace_world across the decal box that must hit the wall 18-42 cm in).
NOT placed here: light (P10-7), gameplay and every record with extras.skip_place (P10-6b: GP_*, TWA_GreatBell).
Every placed actor: ONE full transform call (location+rotation+scale), label = id, outliner folder = record folder; collision per the record:
  NoCollision          -> bUseDefaultCollision=false + bodyInstance.collisionProfileName=NoCollision + collisionEnabled=NoCollision (MCP_NOTES)
  hidden-block         -> BlockAll (engine cube), StaticMeshComponent bVisible=false
  BlockAll (...)       -> the mesh's own simple collision is kept (SM_LB_Tw_BellFrame_A, 4 UCX boxes)
Materials: an override is written only for a slot whose record MI differs from the mesh's own slot material (P10-4); slots the mesh
does not have (UE drops unused slots) are ignored.
"""
import argparse
import json
import math
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp"))
from ue import UE  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
LAYOUT = os.path.join(ROOT, "Docs", "plans", "p10_d1_layout.json")
S = "editor_toolset.toolsets.scene.SceneTools"
A = "editor_toolset.toolsets.actor.ActorTools"
O = "editor_toolset.toolsets.object.ObjectTools"
SM = "editor_toolset.toolsets.static_mesh.StaticMeshTools"
TOL = 3.0
LOC_TOL = 0.5

ORDER = ["block", "wall", "tower", "stair", "arcade", "vault", "roof", "floor", "garth", "door", "doorleaf", "dress"]
WALL_DIR = {"S": (0.0, -1.0, 0.0), "N": (0.0, 1.0, 0.0), "W": (-1.0, 0.0, 0.0), "E": (1.0, 0.0, 0.0)}   # decal forward must point into this wall
GREYBOX_FOLDERS = ["Cloister", "BellTower", "BellTower/Stairs", "BellTower/Railings", "Courtyard"]   # Passage_S/N live in Courtyard


def ang_diff(a, b):
    return (a - b + 180.0) % 360.0 - 180.0


def rot_rows(p, y, r):
    P, Y, R = (math.radians(v) for v in (p, y, r))
    SP, CP, SY, CY, SR, CR = math.sin(P), math.cos(P), math.sin(Y), math.cos(Y), math.sin(R), math.cos(R)
    return [(CP * CY, CP * SY, SP),
            (SR * SP * CY - CR * SY, SR * SP * SY + CR * CY, -SR * CP),
            (-(CR * SP * CY + SR * SY), CY * SR - CR * SP * SY, CR * CP)]


def is_axis_aligned(rot):
    return abs(rot[0]) < 0.01 and abs(rot[2]) < 0.01 and abs(((rot[1] + 45.0) % 90.0) - 45.0) < 0.01


def mref(path):
    return {"refPath": path if "." in path.split("/")[-1] else path + "." + path.split("/")[-1]}


class Placer:
    def __init__(self):
        self.ue = UE()
        self.layout = json.load(open(LAYOUT))
        self.fix_collision = False
        self.mesh_slots = {}      # mesh path -> [(slot name, current MI name)]
        self.folder_cache = {}    # folder -> {label: actor}
        self.decal_rows = []      # (id, forward.wall dot, trace distance, material, size, status)

    def call(self, ts, tool, args=None, tries=4):
        for k in range(tries):
            try:
                return self.ue.call(ts, tool, args)
            except Exception as e:  # connection reset etc.
                if k == tries - 1:
                    raise
                print("  retry %s.%s (%s)" % (tool, ts.split(".")[-1], str(e)[:120]), flush=True)
                time.sleep(2)
                try:
                    self.ue = UE()
                except Exception:
                    time.sleep(3)

    # ---- helpers
    def label(self, a):
        return self.call(A, "get_label", {"actor": a})

    def props(self, comp, names):
        r = self.call(O, "get_properties", {"instance": comp, "properties": names})
        return json.loads(r) if isinstance(r, str) else r

    def set_props(self, comp, values):
        return self.call(O, "set_properties", {"instance": comp, "values": json.dumps(values)})

    def comp0(self, actor):
        return self.call(A, "get_components", {"actor": actor})[0]

    def bounds(self, actor):
        b = self.call(A, "get_actor_bounds", {"actor": actor})
        return [b["min"]["x"], b["min"]["y"], b["min"]["z"]], [b["max"]["x"], b["max"]["y"], b["max"]["z"]]

    def folder_actors(self, folder, refresh=False):
        """{label: actor} of the actors directly in an outliner folder (cached per run unless refresh)."""
        if refresh or folder not in self.folder_cache:
            out = {}
            try:
                acs = self.call(S, "get_actors_in_folder", {"folder_path": folder, "recursive": False}, tries=1) or []
            except Exception as e:
                if "does not exist" in str(e):
                    acs = []
                else:
                    raise
            for a in acs:
                out[self.label(a)] = a
            self.folder_cache[folder] = out
        return self.folder_cache[folder]

    def slots_of(self, mesh):
        if mesh not in self.mesh_slots:
            ref = mref(mesh)
            names = self.call(SM, "get_material_slots", {"mesh": ref}) or []
            lst = []
            for s in names:
                g = self.call(SM, "get_material", {"mesh": ref, "slot_name": s})
                p = (g.get("refPath", "") if isinstance(g, dict) else str(g or ""))
                lst.append((s, p.split(".")[0].rsplit("/", 1)[-1] if p else ""))
            self.mesh_slots[mesh] = lst
        return self.mesh_slots[mesh]

    def mi_path(self, name):
        p = self.layout["mi_paths"][name]
        return {"refPath": p + "." + name}

    def expected_materials(self, rec):
        """(override list with None for slots that keep the mesh material, effective MI names per slot index)"""
        slots = self.slots_of(rec["mesh"])
        want = rec.get("mi_slots") or {}
        ov, eff = [], []
        for s, cur in slots:
            mi = want.get(s)
            if mi and mi != cur:
                ov.append(mi)
                eff.append(mi)
            else:
                ov.append(None)
                eff.append(cur)
        return ov, eff

    def read_state(self, comp):
        p = self.props(comp, ["bUseDefaultCollision", "bodyInstance", "overrideMaterials", "bVisible"])
        bi = p["bodyInstance"]
        mats = [(m["refPath"].split("/")[-1].split(".")[0] if isinstance(m, dict) and m else None) for m in p["overrideMaterials"]]
        return {"profile": bi["collisionProfileName"], "enabled": bi.get("collisionEnabled"), "useDefault": p["bUseDefaultCollision"],
                "visible": p["bVisible"], "mats": mats}

    # ---- placement
    def targets(self, cat, only):
        recs = [r for r in self.layout["placements"] if r["cat"] == cat and (not only or only in r["id"])]
        return [r for r in recs if not (r.get("extras") or {}).get("skip_place")]

    def remove_existing(self, recs):
        n = 0
        for folder in sorted({r["folder"] for r in recs}):
            ids = {r["id"] for r in recs if r["folder"] == folder}
            for lbl, a in list(self.folder_actors(folder, refresh=True).items()):
                if lbl in ids:
                    self.call(S, "remove_from_scene", {"actor": a})
                    n += 1
            self.folder_cache.pop(folder, None)
        return n

    def place_one(self, rec):
        rot = rec["rot"]
        xf = {"location": dict(zip("xyz", rec["loc"])), "rotation": {"pitch": rot[0], "yaw": rot[1], "roll": rot[2]},
              "scale": dict(zip("xyz", rec["scale"]))}
        a = self.call(S, "add_to_scene_from_asset", {"asset_path": rec["mesh"], "name": rec["id"], "xform": xf}, tries=1)
        if not a:
            raise RuntimeError("spawn failed for " + rec["id"] + " " + rec["mesh"])
        self.call(A, "set_actor_transform", {"actor": a, "xform": xf, "worldspace": True})   # one full transform call (never partial)
        self.call(A, "set_label", {"actor": a, "label": rec["id"]})
        self.call(S, "set_actor_folder", {"actor": a, "folder_path": rec["folder"]})
        comp = self.comp0(a)
        vals = {}
        col = rec["collision"]
        if col == "NoCollision":
            vals["bUseDefaultCollision"] = False
            # collisionEnabled must be set explicitly (P9-6a: with only the profile name the live body keeps QueryAndPhysics)
            vals["bodyInstance"] = {"collisionProfileName": "NoCollision", "collisionEnabled": "NoCollision"}
        elif col == "hidden-block":
            vals["bUseDefaultCollision"] = False
            vals["bodyInstance"] = {"collisionProfileName": "BlockAll"}
            vals["bVisible"] = False
        ov, _eff = self.expected_materials(rec)
        if any(ov):
            vals["overrideMaterials"] = [(self.mi_path(m) if m else None) for m in ov]
        if vals:
            self.set_props(comp, vals)
        return a, comp

    def verify(self, rec, a, comp):
        """returns (ok, max bounds deviation, message)"""
        issues = []
        mn, mx = self.bounds(a)
        rot = rec["rot"]
        exp_min, exp_max = rec["aabb_min"], rec["aabb_max"]
        if is_axis_aligned(rot):
            dev = max(max(abs(g - e) for g, e in zip(mn, exp_min)), max(abs(g - e) for g, e in zip(mx, exp_max)))
        else:
            # the expected box is the AABB of the rotated mesh-local box (a superset of the true mesh AABB when the piece is
            # rotated off-axis): only an overhang beyond it counts (P9 rule)
            dev = max(max(e - g for g, e in zip(mn, exp_min)), max(g - e for g, e in zip(mx, exp_max)), 0.0)
        if dev > TOL:
            msg = "bounds dev %.1f (got %s..%s want %s..%s)" % (dev, [round(v, 1) for v in mn], [round(v, 1) for v in mx], exp_min, exp_max)
            if (rec.get("extras") or {}).get("mbounds_estimated"):
                print("  NOTE %s: estimated mesh bounds, measured instead: %s" % (rec["id"], msg), flush=True)
            else:
                issues.append(msg)
        t = self.call(A, "get_actor_transform", {"actor": a, "worldspace": True})
        loc, r, sc = t["location"], t["rotation"], t["scale"]
        dl = max(abs(loc[k] - rec["loc"]["xyz".index(k)]) for k in "xyz")
        dr = max(abs(ang_diff(r["pitch"], rot[0])), abs(ang_diff(r["yaw"], rot[1])), abs(ang_diff(r["roll"], rot[2])))
        ds = max(abs(sc[k] - rec["scale"]["xyz".index(k)]) for k in "xyz")
        if dl > LOC_TOL or dr > 0.1 or ds > 0.001:
            issues.append("transform dev loc %.2f rot %.2f scale %.4f" % (dl, dr, ds))
        st = self.read_state(comp)
        col = rec["collision"]
        if col == "NoCollision":
            if st["profile"] != "NoCollision" or st["useDefault"] or st["enabled"] != "NoCollision":
                issues.append("collision not NoCollision (%s, enabled=%s, useDefault=%s)" % (st["profile"], st["enabled"], st["useDefault"]))
        elif col == "hidden-block":
            if st["visible"] or st["profile"] != "BlockAll" or st["enabled"] == "NoCollision":
                issues.append("hidden-block wrong (visible=%s, profile=%s, enabled=%s)" % (st["visible"], st["profile"], st["enabled"]))
        else:   # BlockAll (...) keeps the mesh's own collision
            if st["profile"] != "BlockAll" or st["enabled"] == "NoCollision":
                issues.append("expected BlockAll, got %s enabled=%s" % (st["profile"], st["enabled"]))
        if col != "hidden-block" and not st["visible"]:
            issues.append("component not visible")
        ov, eff = self.expected_materials(rec)
        got = st["mats"] + [None] * (len(ov) - len(st["mats"]))
        cur = [c for _s, c in self.slots_of(rec["mesh"])]
        for i, want in enumerate(eff):
            actual = got[i] if got[i] else cur[i]
            if rec["collision"] != "hidden-block" and actual != want:
                issues.append("slot %d material %s != %s" % (i, actual, want))
        return not issues, dev, "; ".join(issues)

    # ---- decals (dress records with mesh "Point" and extras.decal; ported from Tools/crypt/place_crypt.py, D1.20)
    @staticmethod
    def is_decal(rec):
        return rec["mesh"] == "Point" and "decal" in (rec.get("extras") or {})

    def place_decal(self, rec):
        rot = rec["rot"]
        xf = {"location": dict(zip("xyz", rec["loc"])), "rotation": {"pitch": rot[0], "yaw": rot[1], "roll": rot[2]},
              "scale": {"x": 1, "y": 1, "z": 1}}                       # the record's rotation exactly as given; scale stays 1
        a = self.call(S, "add_to_scene_from_class", {"actor_type": {"refPath": "/Script/Engine.DecalActor"}, "name": rec["id"], "xform": xf}, tries=1)
        if not a:
            raise RuntimeError("decal spawn failed for " + rec["id"])
        a = a if isinstance(a, dict) else {"refPath": a}
        self.call(A, "set_actor_transform", {"actor": a, "xform": xf, "worldspace": True})
        self.call(A, "set_label", {"actor": a, "label": rec["id"]})
        self.call(S, "set_actor_folder", {"actor": a, "folder_path": rec["folder"]})
        comp = {"refPath": a["refPath"] + ".NewDecalComponent"}
        d = rec["extras"]["decal"]
        sz = d["size"]
        self.set_props(comp, {"decalMaterial": self.mi_path(d["mi"]), "decalSize": {"x": sz[0], "y": sz[1], "z": sz[2]}})
        return a, comp

    def verify_decal(self, rec, a, comp):
        d = rec["extras"]["decal"]
        p = self.props(comp, ["decalMaterial", "decalSize"])
        mat = (p["decalMaterial"] or {}).get("refPath", "").split("/")[-1].split(".")[0]
        sz = p["decalSize"]
        issues = []
        if mat != d["mi"]:
            issues.append("material %s != %s" % (mat, d["mi"]))
        e = d["size"]
        if max(abs(sz["x"] - e[0]), abs(sz["y"] - e[1]), abs(sz["z"] - e[2])) > 0.01:
            issues.append("decalSize %s != %s" % (sz, e))
        t = self.call(A, "get_actor_transform", {"actor": a, "worldspace": True})
        loc, r = t["location"], t["rotation"]
        rot = rec["rot"]
        dl = max(abs(loc[k] - rec["loc"]["xyz".index(k)]) for k in "xyz")
        dr = max(abs(ang_diff(r["pitch"], rot[0])), abs(ang_diff(r["yaw"], rot[1])), abs(ang_diff(r["roll"], rot[2])))
        if dl > 0.1 or dr > 0.1:
            issues.append("transform dev loc %.2f rot %.2f" % (dl, dr))
        # orientation by numbers: forward vector of the read-back rotator must point into the wall
        fwd = rot_rows(r["pitch"], r["yaw"], r["roll"])[0]
        wd = WALL_DIR[d["wall"]]
        dot = sum(f * w for f, w in zip(fwd, wd))
        if dot < 0.999:
            issues.append("forward %s . wall %s = %.4f < 0.999" % ([round(v, 3) for v in fwd], d["wall"], dot))
        # wall inside the box: trace from centre - 30 fwd to centre + 30 fwd must hit 18-42 cm in
        c = rec["loc"]
        s0 = {"x": c[0] - 30 * fwd[0], "y": c[1] - 30 * fwd[1], "z": c[2] - 30 * fwd[2]}
        e0 = {"x": c[0] + 30 * fwd[0], "y": c[1] + 30 * fwd[1], "z": c[2] + 30 * fwd[2]}
        dist = self.call(S, "trace_world", {"start": s0, "end": e0})
        if dist is None or not (18.0 <= dist <= 42.0):
            issues.append("wall trace hit %s (want 18-42)" % ("NONE" if dist is None else "%.1f" % dist))
        self.decal_rows.append((rec["id"], dot, dist, mat, sz, "ok" if not issues else "FAIL"))
        return not issues, dl, "; ".join(issues)

    def block_trace(self, rec):
        """hidden blocks must really block: trace across the thin axis through the centre of the AABB; returns (hit, note)"""
        mn, mx = rec["aabb_min"], rec["aabb_max"]
        ext = [mx[k] - mn[k] for k in range(3)]
        ax = min(range(3), key=lambda k: ext[k])
        c = [(mn[k] + mx[k]) / 2 for k in range(3)]
        a = list(c)
        b = list(c)
        a[ax] = mn[ax] - 30
        b[ax] = c[ax]
        d = self.call(S, "trace_world", {"start": dict(zip("xyz", a)), "end": dict(zip("xyz", b))})
        if d is None:
            return False, "NO HIT"
        return True, "hit at %.1f (expected %.1f)" % (d, 30.0)

    # ---- categories
    def run_cats(self, cats, only, check):
        summary = []
        for cat in cats:
            rs = self.targets(cat, only)
            removed = 0
            if not check:
                removed = self.remove_existing(rs)
            print("== %s: %d records (removed %d existing)" % (cat, len(rs), removed), flush=True)
            fails, maxdev, blocked = [], 0.0, []
            for k, r in enumerate(rs):
                a = None
                if check:
                    a = self.folder_actors(r["folder"], refresh=(k == 0)).get(r["id"])
                    if a is None:
                        fails.append((r["id"], "missing"))
                        print("  FAIL %s: missing" % r["id"], flush=True)
                        continue
                    comp = {"refPath": (a["refPath"] if isinstance(a, dict) else a) + ".NewDecalComponent"} if self.is_decal(r) else self.comp0(a)
                    if self.fix_collision and r["collision"] == "NoCollision":
                        self.set_props(comp, {"bUseDefaultCollision": False,
                                              "bodyInstance": {"collisionProfileName": "NoCollision", "collisionEnabled": "NoCollision"}})
                else:
                    try:
                        a, comp = self.place_decal(r) if self.is_decal(r) else self.place_one(r)
                    except Exception as e:   # one failed record must not abort the run
                        fails.append((r["id"], "place error: " + str(e)[:200]))
                        print("  FAIL %s: place error %s" % (r["id"], str(e)[:200]), flush=True)
                        continue
                try:
                    ok, dev, msg = self.verify_decal(r, a, comp) if self.is_decal(r) else self.verify(r, a, comp)
                except Exception as e:
                    ok, dev, msg = False, 0.0, "verify error: " + str(e)[:200]
                if ok and r["collision"] == "hidden-block":
                    hit, note = self.block_trace(r)
                    blocked.append("%s: %s" % (r["id"], note))
                    if not hit:
                        ok, msg = False, "hidden block does not block a trace"
                maxdev = max(maxdev, dev)
                if not ok:
                    fails.append((r["id"], msg))
                    print("  FAIL %s: %s" % (r["id"], msg), flush=True)
                if (k + 1) % 20 == 0:
                    print("  ..%d/%d" % (k + 1, len(rs)), flush=True)
            for b in blocked:
                print("  trace", b)
            print("   %s: %s %d, pass %d, fail %d, max bounds deviation %.2f cm" %
                  (cat, "checked" if check else "placed", len(rs), len(rs) - len(fails), len(fails), maxdev), flush=True)
            summary.append((cat, len(rs), len(rs) - len(fails), len(fails), maxdev))
        if self.decal_rows:
            print("\nDECALS (id, forward.wall dot, wall trace hit cm, material, decalSize, status)")
            for rid, dot, dist, mat, sz, st in self.decal_rows:
                print("  %-14s dot %.4f  hit %s  %-26s size (%g, %g, %g)  %s" %
                      (rid, dot, "NONE" if dist is None else "%.1f" % dist, mat, sz["x"], sz["y"], sz["z"], st))
        print("\nSUMMARY (cat, n, pass, fail, max dev cm)")
        for s in summary:
            print("  %-9s %4d %4d %3d  %.2f" % s)
        return summary

    # ---- ground (D1.0: the ground slabs seen through the tower / cloister)
    def ground(self):
        gm = self.layout["ground_materials"]
        acs = self.folder_actors("Ground", refresh=True)
        for lbl, path in sorted(gm.items()):
            a = acs.get(lbl)
            if a is None:
                print("  MISSING", lbl)
                continue
            comp = self.comp0(a)
            name = path.rsplit("/", 1)[-1]
            self.set_props(comp, {"overrideMaterials": [{"refPath": path + "." + name}]})
        print("ground slab read-back:")
        ok = True
        for lbl in sorted(acs):
            if not lbl.startswith("Ground_"):
                continue
            st = self.read_state(self.comp0(acs[lbl]))
            want = gm.get(lbl)
            flag = ""
            if want:
                flag = "OK" if st["mats"][:1] == [want.rsplit("/", 1)[-1]] else "MISMATCH"
                ok &= flag == "OK"
            print("  %-9s override %s %s" % (lbl, st["mats"], flag))
        print("ground:", "all %d target slabs carry their material" % len(gm) if ok else "MISMATCH")
        return ok

    # ---- perimeter wall (D1.14a): world-aligned masonry on Perim_N/E/S/W, nothing else touched
    def perim(self):
        pm = self.layout["perimeter_materials"]
        found = {}
        for lbl in sorted(pm):
            hits = self.call(S, "find_actors", {"name": lbl, "tag": "", "collision_channels": []}) or []
            exact = [a for a in hits if self.label(a) == lbl]       # find_actors matches by substring: keep exact labels only
            if len(exact) != 1:
                print("  STOP: %s matched %d actors exactly (%d substring hits: %s)" % (lbl, len(exact), len(hits), [self.label(a) for a in hits]))
                return False
            found[lbl] = exact[0]
        before = {lbl: self.read_state(self.comp0(a)) for lbl, a in found.items()}
        for lbl, st in before.items():
            print("  before %-7s override %s visible %s profile %s enabled %s useDefault %s" %
                  (lbl, st["mats"], st["visible"], st["profile"], st["enabled"], st["useDefault"]))
        for lbl, a in found.items():
            path = pm[lbl]
            self.set_props(self.comp0(a), {"overrideMaterials": [{"refPath": path + "." + path.rsplit("/", 1)[-1]}]})
        ok = True
        for lbl, a in found.items():
            st = self.read_state(self.comp0(a))
            b = before[lbl]
            want = pm[lbl].rsplit("/", 1)[-1]
            mat_ok = st["mats"][:1] == [want]
            same = all(st[k] == b[k] for k in ("visible", "profile", "enabled", "useDefault"))
            print("  after  %-7s override %s visible %s profile %s enabled %s useDefault %s -> material %s, visibility/collision %s" %
                  (lbl, st["mats"], st["visible"], st["profile"], st["enabled"], st["useDefault"], "OK" if mat_ok else "MISMATCH",
                   "unchanged" if same else "CHANGED"))
            ok &= mat_ok and same
        print("perimeter:", "all %d walls carry their material, visibility and collision unchanged" % len(pm) if ok else "MISMATCH")
        return ok

    # ---- greybox (D-078)
    def greybox_actors(self):
        want = set(self.layout["hide_greybox"])
        found = {}
        for fo in GREYBOX_FOLDERS:
            for lbl, a in self.folder_actors(fo, refresh=True).items():
                if lbl in want:
                    found[lbl] = a
        return found, sorted(want - set(found))

    def hide_greybox(self):
        found, missing = self.greybox_actors()
        print("greybox actors found %d / %d, missing %s" % (len(found), len(self.layout["hide_greybox"]), missing))
        before = {}
        for lbl, a in found.items():
            comp = self.comp0(a)
            p = self.props(comp, ["bodyInstance", "bUseDefaultCollision"])
            before[lbl] = (p["bodyInstance"]["collisionProfileName"], p["bodyInstance"].get("collisionEnabled"), p["bUseDefaultCollision"])
        for k, (lbl, a) in enumerate(found.items()):
            self.set_props(self.comp0(a), {"bVisible": False})
            if (k + 1) % 50 == 0:
                print("  ..hidden %d/%d" % (k + 1, len(found)), flush=True)
        return self.verify_greybox(found, before)

    def verify_greybox(self, found=None, before=None):
        if found is None:
            found, missing = self.greybox_actors()
            print("greybox actors found %d / %d, missing %s" % (len(found), len(self.layout["hide_greybox"]), missing))
        bad, changed, profiles = 0, 0, {}
        for lbl, a in found.items():
            p = self.props(self.comp0(a), ["bVisible", "bodyInstance", "bUseDefaultCollision"])
            prof = p["bodyInstance"]["collisionProfileName"]
            profiles[prof] = profiles.get(prof, 0) + 1
            if p["bVisible"] or prof == "NoCollision" or p["bodyInstance"].get("collisionEnabled") == "NoCollision":
                bad += 1
                print("  BAD", lbl, p["bVisible"], prof, p["bodyInstance"].get("collisionEnabled"))
            if before is not None and before[lbl] != (prof, p["bodyInstance"].get("collisionEnabled"), p["bUseDefaultCollision"]):
                changed += 1
                print("  COLLISION CHANGED", lbl, before[lbl], "->", (prof, p["bodyInstance"].get("collisionEnabled"), p["bUseDefaultCollision"]))
        print("greybox read-back: %d actors, still visible or no collision: %d, collision changed vs before: %s, profiles %s" %
              (len(found), bad, changed if before is not None else "n/a", profiles))
        t_ok = self.trace_checks(found)
        return bad == 0 and changed == 0 and t_ok and len(found) == len(self.layout["hide_greybox"])

    def gb_bounds(self, found, lbl):
        return self.bounds(found[lbl])

    def vtrace(self, name, x, y, top, exp_top, found_ok=True):
        d = self.call(S, "trace_world", {"start": {"x": x, "y": y, "z": top + 40}, "end": {"x": x, "y": y, "z": top - 40}})
        hit = None if d is None else top + 40 - d
        ok = hit is not None and abs(hit - exp_top) <= 1.5
        print("  trace %-34s vertical at (%.0f, %.0f): hit z %s (expected %.1f) %s" %
              (name, x, y, "None" if hit is None else "%.2f" % hit, exp_top, "OK" if ok else "FAIL"))
        return ok

    def wall_trace(self, name, bmin, bmax):
        """horizontal trace across the thin axis of a wall box from either side; expected hit on the near face"""
        ext = [bmax[k] - bmin[k] for k in range(3)]
        ax = min(range(2), key=lambda k: ext[k])
        c = [(bmin[k] + bmax[k]) / 2 for k in range(3)]
        for side in (0, 1):
            s, e = list(c), list(c)
            face = bmin[ax] if side == 0 else bmax[ax]
            s[ax] = face - 60 if side == 0 else face + 60
            e[ax] = c[ax]
            d = self.call(S, "trace_world", {"start": dict(zip("xyz", s)), "end": dict(zip("xyz", e))})
            if d is not None:
                ok = abs(d - 60) <= 1.5
                print("  trace %-34s horizontal axis %s from the %s side at z %.0f: hit after %.2f (expected 60.00) %s" %
                      (name, "XY"[ax], "min" if side == 0 else "max", c[2], d, "OK" if ok else "FAIL"))
                return ok
        print("  trace %-34s horizontal axis %s: NO HIT from either side FAIL" % (name, "XY"[ax]))
        return False

    def trace_checks(self, found):
        ok = True
        for lbl in ("Stair_F01_05", "Stair_F06_07", "Stair_F11_13", "Tw_Landing_05", "Garth"):
            if lbl not in found:
                print("  trace %s: greybox actor missing FAIL" % lbl)
                ok = False
                continue
            mn, mx = self.gb_bounds(found, lbl)
            ok &= self.vtrace(lbl + " top", (mn[0] + mx[0]) / 2, (mn[1] + mx[1]) / 2, mx[2], mx[2])
        # tower core, horizontal from the W ring at Z 1200
        mn, mx = self.gb_bounds(found, "Tw_Core")
        cy = (mn[1] + mx[1]) / 2
        x0 = mn[0] - 140
        d = self.call(S, "trace_world", {"start": {"x": x0, "y": cy, "z": 1200}, "end": {"x": mn[0] + 40, "y": cy, "z": 1200}})
        good = d is not None and abs(d - 140) <= 1.5
        print("  trace %-34s horizontal along X at (y %.0f, z 1200) from the W ring: hit after %s (expected 140.00) %s" %
              ("Tw_Core W face", cy, "None" if d is None else "%.2f" % d, "OK" if good else "FAIL"))
        ok &= good
        for lbl in ("Cl_N", "Passage_S"):
            mn, mx = self.gb_bounds(found, lbl)
            ok &= self.wall_trace(lbl, mn, mx)
        print("trace checks:", "all hit" if ok else "SOME FAILED")
        return ok



"""P10-7 bell tower / cloister / passage lighting placement (Unreal MCP). D1.23.
Adapted from Tools/crypt/place_lighting.py (P9-7: greybox removal with dump, LFV, PP) and the `light` category of Tools/crypt/place_crypt.py.
Reads Docs/plans/p10_d1_layout.json (generated by gen_tower_layout.py; never hand-edit it): the 13 `cat == "light"` records and `lights_plan` (delete / fog / pp).

Usage (editor open on L_Monastery, PIE STOPPED; spawning while PIE runs would put the actors in the PIE world):
    python place_lighting_p10.py greybox   # dump the 17 lights_plan.delete lights to Docs/ArtTest/belltower/greybox_lights_before.json, then delete them
    python place_lighting_p10.py lights    # the 13 PointLights (label = id, folder = record folder), values read back
    python place_lighting_p10.py lfv       # LFV_Tower_0..3 (LocalFogVolume), values read back
    python place_lighting_p10.py pp        # PP_Cloister (PostProcessVolume), bounds / flags / overrides read back
    python place_lighting_p10.py check     # read-only: everything above; PASS/FAIL per line, exit 1 on any FAIL

Every placing action is idempotent (removes its own labels first). Only the 17 lights_plan.delete labels are ever deleted; any other light found is only reported.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mcp"))
from ue import UE  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
LAYOUT = os.path.join(ROOT, "Docs", "plans", "p10_d1_layout.json")
DUMP = os.path.join(ROOT, "Docs", "ArtTest", "belltower", "greybox_lights_before.json")
S = "editor_toolset.toolsets.scene.SceneTools"
A = "editor_toolset.toolsets.actor.ActorTools"
O = "editor_toolset.toolsets.object.ObjectTools"
E = "EditorToolset.EditorAppToolset"
LF_DIR = "/Game/LastBell/Materials/Instances/"
LIGHT_FOLDERS = ["Lighting/Cloister", "Lighting/BellTower"]
KNOWN_OTHER = ("Light_TowerExt_", "LFV_Tower_", "PP_Cloister")      # expected non-record residents of the two folders
UE_ = UE()
LAYOUT_J = json.load(open(LAYOUT, encoding="utf-8"))
PLAN = LAYOUT_J["lights_plan"]
LIGHTS = [r for r in LAYOUT_J["placements"] if r["cat"] == "light"]
RES = []        # (ok, text) from check()


def call(ts, tool, args=None):
    return UE_.call(ts, tool, args)


def props(inst, names):
    r = call(O, "get_properties", {"instance": inst if isinstance(inst, dict) else {"refPath": inst}, "properties": names})
    return json.loads(r) if isinstance(r, str) else r


def setp(inst, vals):
    return call(O, "set_properties", {"instance": inst if isinstance(inst, dict) else {"refPath": inst}, "values": json.dumps(vals)})


def find_label(label, exact=True):
    out = []
    for a in call(S, "find_actors", {"name": label, "tag": "", "collision_channels": []}) or []:
        lbl = call(A, "get_label", {"actor": a})
        if (lbl == label) if exact else lbl.startswith(label):
            out.append(a)
    return out


def remove_label(label):
    n = 0
    for a in find_label(label):
        call(S, "remove_from_scene", {"actor": a})
        n += 1
    return n


def xf(loc, rot=(0, 0, 0), sc=(1, 1, 1)):
    return {"location": dict(zip("xyz", loc)), "rotation": {"pitch": rot[0], "yaw": rot[1], "roll": rot[2]}, "scale": dict(zip("xyz", sc))}


def tf(actor):
    t = call(A, "get_actor_transform", {"actor": actor, "worldspace": True})
    return [t["location"][k] for k in "xyz"], [t["rotation"][k] for k in ("pitch", "yaw", "roll")], [t["scale"][k] for k in "xyz"]


def bounds(actor):
    b = call(A, "get_actor_bounds", {"actor": actor})
    return [b["min"][k] for k in "xyz"], [b["max"][k] for k in "xyz"]


def finish(a, label, folder):
    call(A, "set_label", {"actor": a, "label": label})
    call(S, "set_actor_folder", {"actor": a, "folder_path": folder})


def folder_of(label):
    """outliner folder of an actor, found by scanning the Lighting/* folders (and Lighting itself)"""
    for f in call(S, "get_folders") or []:
        if not f.startswith("Lighting"):
            continue
        for a in call(S, "get_actors_in_folder", {"folder_path": f, "recursive": False}) or []:
            if call(A, "get_label", {"actor": a}) == label:
                return f
    return None


def rgb(c):
    return [c["r"], c["g"], c["b"]]


def lf_name(v):
    """short name of a lightFunctionMaterial read-back ('none' when unset; the tool returns a dict with refPath, or a bare string/None)"""
    ref = v.get("refPath", "") if isinstance(v, dict) else (v or "")
    return ref.split("/")[-1].split(".")[-1] if ref and ref.lower() != "none" else "none"


def close(g, e, rel=0.005, absol=1e-6):
    return abs(g - e) <= max(rel * abs(e), absol)


def colour_close(g, e):
    return all(abs(g[i] - e[i]) <= 1.0 / 255 + 1e-4 for i in range(3))


def rec(ok, text):
    RES.append((bool(ok), text))
    print(("PASS  " if ok else "FAIL  ") + text, flush=True)
    return ok


# ------------------------------------------------------------------ greybox
def greybox():
    labels = PLAN["delete"]
    assert len(labels) == 17, labels
    dump = {}
    if os.path.exists(DUMP):
        dump = {d["label"]: d for d in json.load(open(DUMP, encoding="utf-8"))}
    for lbl in labels:
        for a in find_label(lbl):
            comp = {"refPath": a["refPath"] + ".LightComponent0"}
            loc, rot, sc = tf(a)
            dump[lbl] = {"label": lbl, "class": call(O, "get_class", {"instance": a}), "actor": a["refPath"], "folder": folder_of(lbl),
                         "location": loc, "rotation": rot, "scale": sc,
                         "light": props(comp, ["mobility", "intensityUnits", "intensity", "attenuationRadius", "bUseTemperature", "temperature", "lightColor", "castShadows"])}
    missing = [l for l in labels if l not in dump]
    if missing:
        print("labels neither present nor in an earlier dump: %s" % missing)
        return False
    os.makedirs(os.path.dirname(DUMP), exist_ok=True)
    with open(DUMP, "w", encoding="utf-8") as f:
        json.dump([dump[l] for l in labels], f, indent=1)
    print("dumped %d greybox lights to %s" % (len(labels), os.path.relpath(DUMP, ROOT)))
    n = 0
    for lbl in labels:
        n += remove_label(lbl)
    gone = [l for l in labels if not find_label(l)]
    print("removed %d greybox lights; %d/%d labels confirmed gone" % (n, len(gone), len(labels)))
    return len(gone) == len(labels)


# ------------------------------------------------------------------ lights
def light_vals(L):
    v = {"mobility": "Movable", "intensityUnits": "Lumens", "intensity": L["lumens"], "attenuationRadius": L["radius"], "bUseTemperature": False,
         "lightColor": {"r": L["color_linear"][0], "g": L["color_linear"][1], "b": L["color_linear"][2], "a": 1.0},
         "castShadows": bool(L["shadows"]), "volumetricScatteringIntensity": L["volumetric_scattering"], "sourceRadius": L["source_radius"],
         "bCastVolumetricShadow": False}
    if L.get("light_function"):
        n = L["light_function"]
        v["lightFunctionMaterial"] = {"refPath": LF_DIR + n + "." + n}
    return v


def verify_light(r, a):
    L = r["extras"]["light"]
    comp = {"refPath": a["refPath"] + ".LightComponent0"}
    want = light_vals(L)
    names = list(want) + ["lightFunctionMaterial"]
    got = props(comp, names)
    issues = []
    for k, e in want.items():
        g = got.get(k)
        if k == "lightColor":
            if not colour_close(rgb(g), rgb(e)):
                issues.append("lightColor %s != %s" % (rgb(g), rgb(e)))
        elif k == "lightFunctionMaterial":
            if lf_name(g) != L["light_function"]:
                issues.append("lightFunctionMaterial %s" % g)
        elif isinstance(e, (bool, str)):
            if g != e:
                issues.append("%s %s != %s" % (k, g, e))
        elif not close(g, e):
            issues.append("%s %s != %s" % (k, g, e))
    if not L.get("light_function") and lf_name(got.get("lightFunctionMaterial")) != "none":
        issues.append("lightFunctionMaterial should be none, is %s" % got["lightFunctionMaterial"])
    loc, rot, _ = tf(a)
    dl = max(abs(loc[i] - r["loc"][i]) for i in range(3))
    if dl > 0.1:
        issues.append("location dev %.2f (%s vs %s)" % (dl, [round(v, 2) for v in loc], r["loc"]))
    return issues, got, loc


def lights():
    ok = True
    for r in LIGHTS:
        remove_label(r["id"])
        L = r["extras"]["light"]
        t = xf(r["loc"])
        a = call(S, "add_to_scene_from_class", {"actor_type": {"refPath": "/Script/Engine." + L["type"]}, "name": r["id"], "xform": t})
        if not a:
            raise RuntimeError("light spawn failed for " + r["id"])
        a = a if isinstance(a, dict) else {"refPath": a}
        call(A, "set_actor_transform", {"actor": a, "xform": t, "worldspace": True})
        finish(a, r["id"], r["folder"])
        setp({"refPath": a["refPath"] + ".LightComponent0"}, light_vals(L))
        issues, got, loc = verify_light(r, a)
        g = {k: got[k] for k in ("intensity", "intensityUnits", "attenuationRadius", "bUseTemperature", "castShadows", "volumetricScatteringIntensity", "sourceRadius", "bCastVolumetricShadow")}
        print("  %-14s loc %s folder %s color %s lightFunction %s %s -> %s" % (
            r["id"], [round(v, 1) for v in loc], folder_of(r["id"]), [round(v, 4) for v in rgb(got["lightColor"])],
            lf_name(got.get("lightFunctionMaterial")), g, "OK" if not issues else "CHECK " + "; ".join(issues)))
        ok &= not issues
    return ok


# ------------------------------------------------------------------ LFV
def lfv_vals(f):
    return {"radialFogExtinction": f["radialFogExtinction"], "heightFogExtinction": f["heightFogExtinction"], "fogPhaseG": f["fogPhaseG"],
            "fogAlbedo": {"r": f["fogAlbedo"][0], "g": f["fogAlbedo"][1], "b": f["fogAlbedo"][2], "a": 1.0},
            "fogEmissive": {"r": f["fogEmissive"][0], "g": f["fogEmissive"][1], "b": f["fogEmissive"][2], "a": 1.0}}


def lfv_issues(f, a):
    comp = {"refPath": a["refPath"] + ".LocalFogVolumeComponent"}
    want = lfv_vals(f)
    got = props(comp, list(want))
    issues = []
    for k, e in want.items():
        g = got[k]
        if isinstance(e, dict):
            if max(abs(g[c] - e[c]) for c in "rgb") > 1.0 / 255 + 1e-4:
                issues.append("%s %s != %s" % (k, rgb(g), rgb(e)))
        elif not close(g, e, absol=1e-6):
            issues.append("%s %s != %s" % (k, g, e))
    loc, rot, sc = tf(a)
    if max(abs(loc[i] - f["loc"][i]) for i in range(3)) > 0.1 or max(abs(s - f["scale"]) for s in sc) > 1e-3:
        issues.append("transform loc %s scale %s" % (loc, sc))
    return issues, got, loc, sc


def lfv():
    ok = True
    for f in PLAN["fog"]:
        remove_label(f["id"])
        t = xf(f["loc"], (0, 0, 0), (f["scale"],) * 3)
        a = call(S, "add_to_scene_from_class", {"actor_type": {"refPath": "/Script/Engine.LocalFogVolume"}, "name": f["id"], "xform": t})
        call(A, "set_actor_transform", {"actor": a, "xform": t, "worldspace": True})
        finish(a, f["id"], f["folder"])
        setp({"refPath": a["refPath"] + ".LocalFogVolumeComponent"}, lfv_vals(f))
        issues, got, loc, sc = lfv_issues(f, a)
        b = bounds(a)
        print("  %s at %s scale %s bounds %s..%s folder %s: %s -> %s" % (f["id"], [round(v, 1) for v in loc], [round(v, 3) for v in sc], [round(v, 1) for v in b[0]],
                                                                       [round(v, 1) for v in b[1]], folder_of(f["id"]), got, "OK" if not issues else "CHECK " + "; ".join(issues)))
        ok &= not issues
    return ok


# ------------------------------------------------------------------ PP_Cloister
def pp_settings(p):
    s = p["ColorSaturationShadows"]
    return {"settings": {"bOverride_AutoExposureMinBrightness": True, "bOverride_AutoExposureMaxBrightness": True,
                         "autoExposureMinBrightness": p["AutoExposureMinBrightness"], "autoExposureMaxBrightness": p["AutoExposureMaxBrightness"],
                         "bOverride_ColorSaturationShadows": True, "colorSaturationShadows": {"x": s[0], "y": s[1], "z": s[2], "w": s[3]}}}


def pp_issues(p, a):
    issues = []
    g = props(a, ["bUnbound", "priority", "blendRadius", "blendWeight", "settings"])
    st = g["settings"]
    if g["bUnbound"] != p["bUnbound"]:
        issues.append("bUnbound %s" % g["bUnbound"])
    if not close(g["priority"], p["priority"], absol=1e-4):
        issues.append("priority %s" % g["priority"])
    if not close(g["blendRadius"], p["blendRadius"], absol=1e-3):
        issues.append("blendRadius %s" % g["blendRadius"])
    for k in ("AutoExposureMinBrightness", "AutoExposureMaxBrightness"):
        if not st["bOverride_" + k] or not close(st[k[0].lower() + k[1:]], p[k], absol=1e-4):
            issues.append("%s override %s value %s" % (k, st["bOverride_" + k], st[k[0].lower() + k[1:]]))
    cs = st["colorSaturationShadows"]
    cs = [cs[c] for c in ("x", "y", "z", "w")] if isinstance(cs, dict) and "x" in cs else ([cs["r"], cs["g"], cs["b"], cs["a"]] if isinstance(cs, dict) else list(cs))
    if not st["bOverride_ColorSaturationShadows"] or max(abs(cs[i] - p["ColorSaturationShadows"][i]) for i in range(4)) > 1e-4:
        issues.append("ColorSaturationShadows override %s value %s" % (st["bOverride_ColorSaturationShadows"], cs))
    b = bounds(a)
    for i in range(3):
        if abs(b[0][i] - p["box_min"][i]) > 5 or abs(b[1][i] - p["box_max"][i]) > 5:
            issues.append("bounds %s..%s vs box %s..%s" % (b[0], b[1], p["box_min"], p["box_max"]))
            break
    return issues, g, st, b


def pp():
    p = PLAN["pp"]
    remove_label(p["id"])
    lo, hi = p["box_min"], p["box_max"]
    loc = [(lo[i] + hi[i]) / 2.0 for i in range(3)]
    a = call(S, "add_to_scene_from_class", {"actor_type": {"refPath": "/Script/Engine.PostProcessVolume"}, "name": p["id"], "xform": xf(loc)})
    call(A, "set_actor_transform", {"actor": a, "xform": xf(loc), "worldspace": True})
    finish(a, p["id"], p["folder"])
    b0 = bounds(a)
    ext = [b0[1][i] - b0[0][i] for i in range(3)]
    size = [hi[i] - lo[i] for i in range(3)]
    sc = tuple(size[i] / ext[i] for i in range(3))
    print("  default brush bounds %s..%s extent %s -> scale %s" % (b0[0], b0[1], ext, [round(v, 4) for v in sc]))
    call(A, "set_actor_transform", {"actor": a, "xform": xf(loc, (0, 0, 0), sc), "worldspace": True})
    setp(a, {"bUnbound": p["bUnbound"], "blendRadius": p["blendRadius"], "priority": p["priority"], "blendWeight": 1.0})
    setp(a, pp_settings(p))
    issues, g, st, b = pp_issues(p, a)
    print("  %s scale %s bounds %s..%s %s exposure min %s max %s (overrides %s %s) satShadows %s (override %s) folder %s -> %s" % (
        p["id"], [round(v, 4) for v in sc], [round(v, 1) for v in b[0]], [round(v, 1) for v in b[1]],
        {k: g[k] for k in ("bUnbound", "priority", "blendRadius", "blendWeight")}, st["autoExposureMinBrightness"], st["autoExposureMaxBrightness"],
        st["bOverride_AutoExposureMinBrightness"], st["bOverride_AutoExposureMaxBrightness"], st["colorSaturationShadows"], st["bOverride_ColorSaturationShadows"],
        folder_of(p["id"]), "OK" if not issues else "CHECK " + "; ".join(issues)))
    return not issues


# ------------------------------------------------------------------ check
def check():
    # 1. greybox lights absent
    for lbl in PLAN["delete"]:
        rec(not find_label(lbl), "greybox light %s is absent" % lbl)
    # 2. the 13 lights
    for r in LIGHTS:
        found = find_label(r["id"])
        if len(found) != 1:
            rec(False, "%s: %d actors found" % (r["id"], len(found)))
            continue
        issues, got, loc = verify_light(r, found[0])
        fo = folder_of(r["id"])
        if fo != r["folder"]:
            issues.append("folder %s != %s" % (fo, r["folder"]))
        rec(not issues, "%s %s lm radius %s color %s lf %s scat %s src %s shadows %s loc %s folder %s%s" % (
            r["id"], got["intensity"], got["attenuationRadius"], [round(v, 3) for v in rgb(got["lightColor"])],
            lf_name(got.get("lightFunctionMaterial")), got["volumetricScatteringIntensity"], got["sourceRadius"],
            got["castShadows"], [round(v, 1) for v in loc], fo, "" if not issues else " :: " + "; ".join(issues)))
    cl = [r for r in LIGHTS if r["id"].startswith(("L_Cl_", "L_Ps_"))]
    tw = [r for r in LIGHTS if r["id"].startswith("L_Tw_")]
    rec(len(cl) == 7 and all(r["folder"] == "Lighting/Cloister" for r in cl), "7 L_Cl_/L_Ps_ records are in Lighting/Cloister")
    rec(len(tw) == 6 and all(r["folder"] == "Lighting/BellTower" for r in tw), "6 L_Tw_ records are in Lighting/BellTower")
    # 3. other residents of the two folders (reported, never deleted)
    expected = {r["id"] for r in LIGHTS}
    for fo in LIGHT_FOLDERS:
        others = []
        for a in call(S, "get_actors_in_folder", {"folder_path": fo, "recursive": False}) or []:
            lbl = call(A, "get_label", {"actor": a})
            if lbl in expected:
                continue
            others.append((lbl, call(O, "get_class", {"instance": a}).get("refPath", "?").split(".")[-1]))
        known = [o for o in others if o[0].startswith(KNOWN_OTHER)]
        unknown = [o for o in others if not o[0].startswith(KNOWN_OTHER)]
        print("INFO  %s other residents: expected %s; UNEXPECTED %s" % (fo, known, unknown))
    # 4. LFVs
    for f in PLAN["fog"]:
        found = find_label(f["id"])
        if len(found) != 1:
            rec(False, "%s: %d actors found" % (f["id"], len(found)))
            continue
        issues, got, loc, sc = lfv_issues(f, found[0])
        fo = folder_of(f["id"])
        if fo != f["folder"]:
            issues.append("folder %s != %s" % (fo, f["folder"]))
        rec(not issues, "%s at %s scale %s %s folder %s%s" % (f["id"], [round(v, 1) for v in loc], [round(v, 3) for v in sc], got, fo, "" if not issues else " :: " + "; ".join(issues)))
    # 5. PP_Cloister
    p = PLAN["pp"]
    found = find_label(p["id"])
    if len(found) != 1:
        rec(False, "%s: %d actors found" % (p["id"], len(found)))
    else:
        issues, g, st, b = pp_issues(p, found[0])
        fo = folder_of(p["id"])
        if fo != p["folder"]:
            issues.append("folder %s != %s" % (fo, p["folder"]))
        rec(not issues, "%s bounds %s..%s %s min %s max %s satShadows %s folder %s%s" % (
            p["id"], [round(v, 1) for v in b[0]], [round(v, 1) for v in b[1]], {k: g[k] for k in ("bUnbound", "priority", "blendRadius")},
            st["autoExposureMinBrightness"], st["autoExposureMaxBrightness"], st["colorSaturationShadows"], fo, "" if not issues else " :: " + "; ".join(issues)))
    # 6. Light_TowerExt_0..2 untouched (300 lm)
    for i in range(3):
        lbl = "Light_TowerExt_%d" % i
        found = find_label(lbl)
        if len(found) != 1:
            rec(False, "%s: %d actors found" % (lbl, len(found)))
            continue
        g = props({"refPath": found[0]["refPath"] + ".LightComponent0"}, ["intensity", "intensityUnits", "attenuationRadius", "castShadows"])
        rec(close(g["intensity"], 300) and g["intensityUnits"] == "Lumens", "%s untouched: %s" % (lbl, g))
    bad = [t for ok, t in RES if not ok]
    print("CHECK SUMMARY: %d PASS, %d FAIL" % (len(RES) - len(bad), len(bad)))
    return not bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["greybox", "lights", "lfv", "pp", "check"])
    a = ap.parse_args()
    if call(E, "IsPIERunning"):
        sys.exit("PIE is running: stop it first (spawned actors would go to the PIE world)")
    if not str(call(S, "get_current_level")).endswith("L_Monastery"):
        sys.exit("editor is not on L_Monastery")
    ok = {"greybox": greybox, "lights": lights, "lfv": lfv, "pp": pp, "check": check}[a.what]()
    print("RESULT", a.what, "OK" if ok else "CHECK")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()

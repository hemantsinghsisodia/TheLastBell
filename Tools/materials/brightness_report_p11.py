"""P11-8: brightness against the Phase 11 baseline and against the earlier phases' targets. No editor needed.

    python -I Tools/materials/brightness_report_p11.py [--final p11_f1_] [--targets p11_t1_] [--out Docs/ArtTest/materials/p11_8_brightness.md]

Luma is the project's B2: Y = 0.2126 R + 0.7152 G + 0.0722 B on the PNG's 8-bit sRGB values / 255, no linearisation.

Baseline: p11_base_<pose>.png against <final><pose>.png. The editor viewport changed size during the phase with a fixed horizontal field of view, so when
sizes differ the final image is scaled to the baseline's width and both are centre-cropped to the shorter height before measuring. Ratio = final mean / baseline mean.

Targets: the numbers below come from D-058, P8_CHAPEL_ART (Targets), P9_CRYPT_ART (Targets (a)) and P10_BELLTOWER_ART (D1.25). Each row says pass or MISS; views with
no number to meet (readability only) are listed for a human to judge.
"""
import argparse
import glob
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DIR = os.path.join(ROOT, "Docs", "ArtTest", "materials")
W = np.array([0.2126, 0.7152, 0.0722])

# view: (metric, low, high, source). None = no bound on that side.
T = {
    "t7_courtyard_to_chapel": [("mean", 0.04, 0.07, "D-058")],
    "t8_entrance": [("mean", 0.04, 0.08, "P8"), ("lt002", 0.15, None, "P8"), ("p99", 0.25, None, "P8"), ("max", 0.9, None, "P8")],
    "t8_midnave": [("mean", 0.04, 0.08, "P8"), ("lt002", 0.15, None, "P8"), ("p99", 0.25, None, "P8"), ("max", 0.9, None, "P8")],
    "t8_sacristy": [("mean", 0.03, 0.08, "P8")],
    "t10_lt_cl_s_entry": [("mean", 0.04, 0.08, "P10")],
    "t10_lt_bell_top": [("centre10", 0.08, None, "P10")],
}
for n in ["01_stair_foot", "02_landing", "03_WC", "04_SC", "05_ossuary_from_J4", "06_ossuary_across", "07_FP_ledge", "08_CC_from_J6", "09_puzzle_wall", "10_NC_gate"]:
    T["t9_" + n] = [("mean", 0.012, 0.035, "P9"), ("lt002", 0.55, None, "P9"), ("p99", 0.30, None, "P9")]
# Accepted values from earlier reviews, where the view passed its review while missing a target by a small amount. Compared with these too.
ACCEPTED = {"t10_lt_cl_s_entry": ("mean", 0.038), "t7_courtyard_to_chapel": ("mean", 0.065)}


def luma(a):
    return (np.asarray(a, dtype=np.float64) / 255.0) @ W


def stats(y):
    h, w = y.shape
    c = y[int(h * .45):int(h * .55), int(w * .45):int(w * .55)]
    return {"mean": float(y.mean()), "lt002": float((y < .02).mean()), "p99": float(np.percentile(y, 99)), "max": float(y.max()), "centre10": float(np.median(c))}


def fit(a, b):
    """a, b are PIL images; return arrays of the same framing."""
    if a.size != b.size:
        b = b.resize((a.size[0], round(b.size[1] * a.size[0] / b.size[0])), Image.LANCZOS)
    h = min(a.size[1], b.size[1])
    def crop(i):
        t = (i.size[1] - h) // 2
        return np.asarray(i.crop((0, t, i.size[0], t + h)).convert("RGB"))
    return crop(a), crop(b)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--final", default="p11_f1_")
    ap.add_argument("--targets", default="p11_t1_")
    ap.add_argument("--out", default=os.path.join(DIR, "p11_8_brightness.md"))
    a = ap.parse_args()
    L = ["# P11-8 brightness", "", "Generated by `Tools/materials/brightness_report_p11.py` (final `%s`, targets `%s`). B2 luma." % (a.final, a.targets), "", "## Against the Phase 11 baseline", "", "| View | Baseline mean | Final mean | Ratio | Max, baseline | Max, final |", "|---|---|---|---|---|---|"]
    out_of = 0
    rows = []
    for f in sorted(glob.glob(os.path.join(DIR, "p11_base_*.png"))):
        n = os.path.basename(f)[len("p11_base_"):-4]
        g = os.path.join(DIR, a.final + n + ".png")
        if not os.path.exists(g):
            L.append("| `%s` | | MISSING | | | |" % n)
            continue
        x, y = fit(Image.open(f).convert("RGB"), Image.open(g).convert("RGB"))
        sx, sy = stats(luma(x)), stats(luma(y))
        r = sy["mean"] / max(sx["mean"], 1e-6)
        rows.append(r)
        L.append("| `%s` | %.4f | %.4f | %.2f | %.3f | %.3f |" % (n, sx["mean"], sy["mean"], r, sx["max"], sy["max"]))
    if rows:
        L += ["", "Ratio: lowest %.2f, median %.2f, highest %.2f." % (min(rows), float(np.median(rows)), max(rows))]
    L += ["", "## Against the earlier phases' targets", "", "| View | Metric | Value | Target | Result |", "|---|---|---|---|---|"]
    misses = []
    seen = set()
    for f in sorted(glob.glob(os.path.join(DIR, a.targets + "*.png"))):
        n = os.path.basename(f)[len(a.targets):-4]
        seen.add(n)
        s = stats(luma(Image.open(f).convert("RGB")))
        if n not in T:
            L.append("| `%s` | mean | %.4f | judge by eye | - |" % (n, s["mean"]))
            continue
        for m, lo, hi, src in T[n]:
            ok = (lo is None or s[m] >= lo) and (hi is None or s[m] <= hi)
            band = "%s to %s" % (lo, hi) if lo is not None and hi is not None else (">= %s" % lo if lo is not None else "<= %s" % hi)
            L.append("| `%s` | %s | %.4f | %s (%s) | %s |" % (n, m, s[m], band, src, "pass" if ok else "**MISS**"))
            if not ok:
                misses.append((n, m, s[m], band))
    for n in sorted(set(T) - seen):
        L.append("| `%s` | | | | MISSING |" % n)
    L += ["", "%d target misses." % len(misses)]
    text = "\n".join(L) + "\n"
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

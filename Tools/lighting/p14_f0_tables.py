"""P14 F0: write Docs/ArtTest/lighting/p14_f0_tables.md from p14_f0_inventory.json (offline; no editor).

    python -I Tools/lighting/p14_f0_tables.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
D = os.path.join(ROOT, "Docs", "ArtTest", "lighting")


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append("| " + " | ".join("" if c is None else str(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def fmt(v, nd=1):
    if isinstance(v, float):
        return ("%." + str(nd) + "f") % v
    return v


def col(c):
    if not c:
        return None
    return "(%.2f, %.2f, %.2f)" % (c["r"], c["g"], c["b"])


def main():
    inv = json.load(open(os.path.join(D, "p14_f0_inventory.json"), encoding="utf-8"))
    h = inv["header"]
    md = ["# P14 F0 survey: tables\n",
          "Generated by `Tools/lighting/p14_f0_tables.py` from `p14_f0_inventory.json` (written by "
          "`Tools/lighting/p14_f0_survey.py`, read-only). Survey time %s; level `%s`; PIE off; map dirty before %s, after %s; "
          "%d editor calls in %d s; %d call errors.\n" % (h["time"], h["level"], h["dirty_before"], h.get("dirty_after"),
                                                         h.get("calls", 0), h.get("seconds", 0), len(inv.get("errors", [])))]

    c = inv["actor_census"]
    md.append("## 1. Actor census\n")
    md.append("**%d actors** (`find_actors` with an empty name and tag). P14-3's final check expects this + 23 = **%d**, "
              "counted the same way.\n" % (c["count"], c["count"] + 23))
    md.append(table(["Class", "Count"], sorted(c["by_class"].items(), key=lambda kv: -kv[1])[:30]))
    md.append("\nExisting storm tags: %s.\n" % ", ".join("`%s` %d" % kv for kv in inv["existing_storm_tags"].items()))
    md.append("\nNew-name collisions (labels the plan will create): %s.\n" %
              ", ".join("`%s` %s" % (k, v or "none") for k, v in inv["new_name_collisions"].items()))

    md.append("\n## 2. Lights the plan names (sections 7.1 and 8)\n")
    rows = []
    for lab, v in inv["plan_light_check"].items():
        rows.append([v["group"], "`%s`" % lab, v["found"], v["class"], v["mobility"], fmt(v["intensity"])])
    md.append(table(["Use", "Label", "Found", "Class", "Mobility", "Intensity"], rows))
    md.append("\n**Crypt torches (250 lm, D-072 T1–T3):** %s\n" % "; ".join(
        "`%s` %s r %s %s" % (t["label"], fmt(t["intensity"]), fmt(t["radius"]), t["loc"]) for t in inv["crypt_torches"]))
    md.append("\n**Crypt niche candles (90 lm):** %s\n" % "; ".join(
        "`%s` %s" % (t["label"], t["loc"]) for t in inv["crypt_niche_candles"]))
    md.append("\n**Flame meshes (`SM_LB_Prop_CandleFlame_A`) within 120 cm of a group light:**\n")
    md.append(table(["Light", "Flames (distance cm)"], [[k, ", ".join("`%s` %.0f" % (f["flame"], f["dist"]) for f in v) or "none"]
                                                       for k, v in inv["flames_near_group_lights"].items()]))
    md.append("\n**Lanterns within 150 cm of a group light:**\n")
    md.append(table(["Light", "Lanterns (distance cm)"], [[k, ", ".join("`%s` %.0f" % (f["lantern"], f["dist"]) for f in v) or "none"]
                                                         for k, v in inv["lanterns_near_group_lights"].items()]))

    md.append("\n## 3. Every placed light\n")
    rows = []
    for L in sorted(inv["lights"], key=lambda L: (L["area"], L["label"] or "")):
        p = L["props"]
        rows.append([L["area"], "`%s`" % L["label"], L["class"], p.get("mobility"), fmt(p.get("intensity"), 2),
                     p.get("intensityUnits"), fmt(p.get("attenuationRadius"), 0), p.get("castShadows"),
                     p.get("castVolumetricShadow"), fmt(p.get("volumetricScatteringIntensity"), 2), p.get("lightFunctionMaterial"),
                     col(p.get("lightColor")), L["xf"]["loc"] if L["xf"] else None, ",".join(L["tags"]) or None])
    md.append(table(["Area", "Label", "Class", "Mobility", "Intensity", "Units", "Radius", "Shadow", "Vol. shadow", "Scatter",
                     "Light fn", "Colour", "Location", "Tags"], rows))
    mob = {}
    for L in inv["lights"]:
        mob[L["props"].get("mobility")] = mob.get(L["props"].get("mobility"), 0) + 1
    md.append("\nMobility: %s.\n" % ", ".join("%s %d" % kv for kv in mob.items()))
    md.append("\n**Lights inside Blueprints (never in a light group):**\n")
    md.append(table(["Actor", "Class", "Light components"], [[b["label"], b["class"], ", ".join(
        "%s (%s, %s)" % (x["component"], fmt(x["props"].get("intensity")), x["props"].get("mobility")) for x in b["lights"])]
        for b in inv["blueprint_lights"]]))

    md.append("\n## 4. Post-process volumes\n")
    rows = []
    for v in inv["pp_volumes"]:
        val = v["values"]
        ev = (val.get("autoExposureMinBrightness"), val.get("autoExposureMaxBrightness"))
        b = v["bounds"]
        rows.append(["`%s`" % v["label"], v["props"].get("bUnbound"), fmt(v["props"].get("priority")),
                     fmt(v["props"].get("blendRadius"), 0), val.get("autoExposureMethod"), ev,
                     fmt(val.get("autoExposureBias"), 2), "%s..%s" % (b["min"], b["max"]) if b and not v["props"].get("bUnbound") else "-",
                     ", ".join(sorted(k for k in v["overrides"] if not k.startswith("AutoExposure")))])
    md.append(table(["Volume", "Unbound", "Priority", "Blend", "Metering", "EV min/max", "Bias", "Bounds", "Other overrides"], rows))

    md.append("\n## 5. Sky\n")
    for s in inv["sky_chain"]:
        md.append("- `%s`%s%s\n" % (s["path"], (" (parent `%s`)" % s.get("parent")) if s.get("parent") else "",
                                     ("; " + s["note"]) if s.get("note") else ""))
        for k in ("scalars", "vectors", "textures"):
            if s.get(k):
                md.append("  - %s: %s\n" % (k, ", ".join("`%s` %s" % (a, b) for a, b in s[k].items())))
    sky = inv["users"]["M_Sky_Panning_Clouds2"]
    md.append("\nSky dome actors: %s\n" % ", ".join("`%s` (%s, %s)" % (u["label"], u["mesh"], u["effective"]) for u in sky))

    md.append("\n## 6. Glass, shafts, light pools, chalk\n")
    md.append(table(["Glass actor", "MIs", "Centre", "Sky behind", "Sky side"],
                    [["`%s`" % g["label"], ", ".join(g["mis"]), g["center"], g["sky_behind"], ",".join(g["sky_side"]) or "-"]
                     for g in inv["glass_sky_test"]]))
    md.append("\nGlass Blueprint users: %s\n" % (", ".join("`%s`" % b.rsplit("/", 1)[-1] for b in inv["glass_bp_users"]) or "none"))
    md.append("\n" + table(["Shaft actor", "Mesh", "MIs", "Location"],
                           [["`%s`" % u["label"], u["mesh"], ", ".join(u["family_mis"]), u["xf"]["loc"] if u["xf"] else None]
                            for u in inv["users"]["M_LB_LightShaft"]]))
    md.append("\n" + table(["Pool decal", "MI", "Size", "Location", "Rotation"],
                           [["`%s`" % p["label"], p["mat"], p["size"], p["xf"]["loc"] if p["xf"] else None,
                             p["xf"]["rot"] if p["xf"] else None] for p in inv["pool_decals"]]))
    md.append("\nChalk decals: %d (%s).\n" % (len(inv["chalk_decals"]), ", ".join(sorted({d["mat"] for d in inv["chalk_decals"]}))))
    for famname in ("M_LB_StainedGlass", "M_LB_StainedGlass_Translucent", "M_LB_LightShaft", "M_LB_Decal_LightPool", "M_LB_Decal_Chalk"):
        f = inv["material_families"].get(famname, {})
        md.append("\n**`%s` MIs:**\n" % famname)
        md.append(table(["MI", "Parent", "In map", "Mesh users", "Scalars", "Vectors"],
                        [["`%s`" % x["path"].rsplit("/", 1)[-1], x["parent"], x["in_map"],
                          ", ".join(m.rsplit("/", 1)[-1] for m in x["mesh_users"]) or "-",
                          ", ".join("%s %s" % (k, fmt(v, 3)) for k, v in x["scalars"].items()) or "-",
                          ", ".join("%s %s" % (k, v) for k, v in x["vectors"].items()) or "-"] for x in f.get("mis", [])]))

    md.append("\n## 7. Foliage\n")
    for famname in ("M_LB_Foliage", "M_LB_FoliageMasked"):
        f = inv["material_families"].get(famname, {})
        md.append("\n**`%s` MIs:**\n" % famname)
        md.append(table(["MI", "Parent", "In map", "Mesh users", "Scalars"],
                        [["`%s`" % x["path"].rsplit("/", 1)[-1], x["parent"], x["in_map"],
                          ", ".join(m.rsplit("/", 1)[-1] for m in x["mesh_users"]) or "-",
                          ", ".join("%s %s" % (k, fmt(v, 3)) for k, v in x["scalars"].items()) or "-"] for x in f.get("mis", [])]))
    md.append("\nPlaced static-mesh actors on a foliage MI, by MI: %s\n" %
              ", ".join("`%s` %d" % kv for kv in inv["foliage_actor_mi_counts"].items()))
    ps = inv["pcg_summary"]
    md.append("\n**PCG:** %d volumes, %d ISM components, %d instances; %d shadow-casting components; "
              "WPO disable distance %s; WPO evaluate %s; shadow cache invalidation %s.\n" %
              (ps["volumes"], ps["ism_components"], ps["instances"], ps["shadow_casting_components"],
               ps["wpo_dist_values"], ps["wpo_eval_values"], ps["sci_values"]))
    md.append(table(["Mesh", "ISM components", "Instances"], [[m, n, ps["instances_by_mesh"].get(m)] for m, n in ps["by_mesh"].items()]))
    md.append("\n" + table(["Group", "Count", "Meshes", "WPO disable distance", "Shadow-casting"],
                           [[k, v["count"], ", ".join("%s %d" % kv for kv in v["mesh_counts"].items()), v["wpo_dist_values"],
                             v["shadow_true"]] for k, v in inv["plant_groups"].items()]))
    md.append("\nSearsia actors: %s\n" % (", ".join("`%s` %s" % (s["label"], s["loc"]) for s in inv["searsia_actors"]) or "none"))
    g = inv.get("garth_bounds")
    if g:
        md.append("\n**`SZN_Garth` box:** X %.0f … %.0f, Y %.0f … %.0f (%s; %d actors).\n" % (g["x"][0], g["x"][1], g["y"][0], g["y"][1],
                                                                                         g["rule"], g["from"]))

    md.append("\n## 8. Apparitions\n")
    for a in inv["apparitions"]:
        st = a["props"].get("stations") or []
        md.append("- `%s` at %s: %d station(s); trigger %s\n" % (a["label"], a["xf"]["loc"] if a["xf"] else None, len(st),
                                                                 a["props"].get("triggerTag")))

    md.append("\n## 9. Reveal decal points (traces)\n")
    md.append("Raw trace results. The resolved placements are in `Docs/plans/P14_LIGHTING_STORM.md` section 5.6(d). "
              "The cloister and tower art meshes have no collision, so traces there hit the hidden greybox; their planes come "
              "from the P10 layout tables (`Docs/plans/p10_d1_tables.md`).\n")
    for k, v in inv["decal_points"].items():
        md.append("\n**`%s`:** %s\n" % (k, json.dumps({kk: vv for kk, vv in v.items() if not kk.startswith("sweep")})))

    md.append("\n## 10. Tower-reveal pose `p14_cy_tower_reveal`\n")
    md.append("```\n%s\n```\n" % json.dumps(inv["tower_reveal_pose"], indent=1))

    md.append("\n## 11. Viewpoints\n")
    md.append("Missing from `p11_poses.json`: %s. New: %s.\n" % (inv["viewpoints"]["missing_from_p11_poses"] or "none",
                                                                 inv["viewpoints"]["new"]))
    if inv.get("errors"):
        md.append("\n## 12. Call errors\n")
        md.append(table(["Context", "Tool", "Error"], [[e["ctx"][-80:], e["tool"], e["error"][:160]] for e in inv["errors"][:60]]))
    out = os.path.join(D, "p14_f0_tables.md")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(x if x.endswith("\n") else x + "\n" for x in md))
    print("wrote", out)


if __name__ == "__main__":
    main()
